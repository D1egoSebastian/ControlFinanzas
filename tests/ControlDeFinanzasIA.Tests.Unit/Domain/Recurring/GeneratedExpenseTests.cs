using ControlDeFinanzasIA.Domain.Enums;
using ControlDeFinanzasIA.Domain.Transactions;
using ControlDeFinanzasIA.Domain.ValueObjects;
using Xunit;

namespace ControlDeFinanzasIA.Tests.Unit.Domain.Recurring;

public sealed class GeneratedExpenseTests
{
    [Fact]
    public void Update_ChangesMovementWithoutMutatingProvenance()
    {
        var ruleId = Guid.NewGuid();
        DateOnly period = new(2026, 2, 1);
        var expense = Expense.CreateGenerated(Guid.NewGuid(), new DateOnly(2026, 2, 28),
            Money.Create(100m, Currency.DOP), "Rent", null, DateTime.UtcNow, Guid.NewGuid(), ruleId, period);

        expense.Update(expense.CategoryId, expense.Date, Money.Create(125m, Currency.DOP), "Rent adjusted", null,
            DateTime.UtcNow.AddMinutes(1), expense.PaymentMethodId);

        Assert.Equal(125m, expense.Amount.Amount);
        Assert.Equal("Rent adjusted", expense.Description);
        Assert.Equal(ruleId, expense.RecurringRuleId);
        Assert.Equal(period, expense.RecurringPeriod);
        Assert.True(expense.IsAutoGenerated);
    }
}
